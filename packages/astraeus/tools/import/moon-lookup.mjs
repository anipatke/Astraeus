// Generates src/core/bodies/listedMoons.ts (O-049 T-210): the slim lookup of every moon in data/moons/<planet>.json that has an ephemeris pointer.
//   node tools/import/moon-lookup.mjs
// `addBody` needs only a moon's id, label, mean radius, parent, orbit period, data package and fit-set body, so this table carries just those and the
// full lists (families, sources, notes: ~160 kB) stay out of the first download. tests/listedMoons.test.ts fails if the table disagrees with the lists.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../", import.meta.url);
export const PLANETS = ["mars", "jupiter", "saturn", "uranus", "neptune", "pluto"];

/** The generated module's text, from the lists under `data/moons/`. */
export function renderListedMoons() {
  const seen = new Set();
  const groups = PLANETS.map((planet) => {
    const list = JSON.parse(readFileSync(new URL(`data/moons/${planet}.json`, root), "utf8"));
    const moons = list.moons.filter((moon) => moon.ephemeris !== undefined && moon.ephemeris !== null);
    const sets = new Set(moons.map((moon) => moon.ephemeris.set));
    if (sets.size > 1) throw new Error(`${planet}: moons point at more than one fit set`);
    // The years each fit covers come from the shipped index (the package's own span, or a body's own): a moon fitted back before 2010 is "early".
    const index = JSON.parse(readFileSync(new URL(`../astraeus-data-${planet}/data/${[...sets][0]}/index.json`, root), "utf8"));
    const from = (id) => Number(((index.bodies.find((body) => body.id === (moons.find((moon) => moon.id === id)).ephemeris.body) ?? {}).span ?? index.span).fromUtc.slice(0, 4));
    const early = moons.filter((moon) => from(moon.id) < 2010).map((moon) => moon.id);
    const rows = moons.map((moon) => {
      if (seen.has(moon.id)) throw new Error(`moon id ${moon.id} is in two lists`);
      seen.add(moon.id);
      // [id, label, mean radius km, orbit period days or null], then the fit-set body only when it is not the id.
      const row = [moon.id, moon.name, moon.meanRadiusKm, moon.orbitPeriodDays ?? null];
      if (moon.ephemeris.body !== moon.id) row.push(moon.ephemeris.body);
      return `    ${JSON.stringify(row)},`;
    });
    return `  ${planet}: { fitSet: ${JSON.stringify([...sets][0])}, early: ${JSON.stringify(early)}, moons: [\n${rows.join("\n")}\n  ] },`;
  });
  return `// GENERATED by tools/import/moon-lookup.mjs from data/moons/<planet>.json; do not edit by hand (run the script after the lists change).
// Every listed moon addBody can place, without the full lists: id, label, mean radius, parent, orbit period (JPL SSD mean elements), data package, fit-set body, whether the fit starts in 1950.
type Row = readonly [id: string, label: string, meanRadiusKm: number, orbitPeriodDays: number | null, fitBody?: string];

export interface ListedMoon {
  readonly id: string;
  readonly label: string;
  readonly meanRadiusKm: number;
  readonly parent: string;
  /** Sidereal orbit period, days; null when no period is published. */
  readonly orbitPeriodDays: number | null;
  /** The data package that holds the moon's fit: \`astraeus-data-<parent>\`. */
  readonly dataPackage: string;
  readonly fitSet: string;
  readonly fitBody: string;
  /** True when the fit starts in 1950 (the main moons); false when it starts in 2010. */
  readonly early: boolean;
}

const TABLE: Readonly<Record<string, { readonly fitSet: string; readonly early: readonly string[]; readonly moons: readonly Row[] }>> = {
${groups.join("\n")}
};

const BY_ID = new Map<string, ListedMoon>();
for (const [parent, { fitSet, early, moons }] of Object.entries(TABLE)) {
  const earlyIds = new Set(early);
  for (const [id, label, meanRadiusKm, orbitPeriodDays, fitBody] of moons) {
    BY_ID.set(id, Object.freeze({ id, label, meanRadiusKm, parent, orbitPeriodDays, dataPackage: \`astraeus-data-\${parent}\`, fitSet, fitBody: fitBody ?? id, early: earlyIds.has(id) }));
  }
}

/** The listed moon with this id, or undefined. */
export const listedMoon = (id: string): ListedMoon | undefined => BY_ID.get(id);

/** Every listed moon, in list order by parent. */
export const listedMoons = (): readonly ListedMoon[] => [...BY_ID.values()];
`;
}

if (process.argv[1] !== undefined && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  writeFileSync(new URL("src/core/bodies/listedMoons.ts", root), renderListedMoons());
  console.log("wrote src/core/bodies/listedMoons.ts");
}
